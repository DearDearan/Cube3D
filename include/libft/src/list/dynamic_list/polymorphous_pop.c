#include "dynamic_list.h"

t_elem	ft_arr_pop_left(void **arr)
{
	t_header	*header;
	t_elem		res;

	header = (t_header *)(*arr) - 1;
	res = *((t_elem *)*arr);
	header->count -= 1;
	ft_memmove(*arr, *arr + 1, header->capacity - 1);
	return (res);
}
